import traceback

app = Flask(__name__)
CORS(app)   # Allow frontend (any origin) to call this backend

# ── Load model once at startup ────────────────────────────
print("Loading loan_model.pkl ...")
artifact     = joblib.load("loan_model.pkl")
model        = artifact["model"]
le_dict      = artifact["le_dict"]
feature_cols = artifact["feature_cols"]
print(f"Model loaded. Features: {len(feature_cols)}")


# ── Feature Engineering (mirrors notebook Cell 5) ─────────
def engineer_features(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    drop_cols = ["applicant_id", "sanctioned_amount_lakhs",
                 "internal_score", "loan_purpose", "loan_approved"]
    df.drop(columns=[c for c in drop_cols if c in df.columns],
            inplace=True)

    df["foir_compliant"]         = (df["foir"] <= 0.50).astype(int)
    df["income_emi_ratio"]       = (df["monthly_income_lakhs"] / (df["emi_lakhs"] + 1e-6)).round(4)
    df["total_obligation_ratio"] = ((df["emi_lakhs"] + df["existing_emi_lakhs"]) / (df["monthly_income_lakhs"] + 1e-6)).round(4)
    df["loan_collateral_gap"]    = (df["loan_amount_lakhs"] - df["collateral_value_lakhs"]).round(4)
    df["employment_score"]       = df["employment_type"].map({
        "Government": 5, "PSU": 4, "Salaried": 3,
        "Self-Employed Professional": 3, "Self-Employed Business": 2
    }).fillna(2)
    df["risk_adj_income"]        = (
        df["annual_income_lakhs"]
        * (1 - 0.15 * df["previous_defaults"])
        * (1 - 0.30 * df["bankruptcies"])
    ).round(4)
    df["retirement_gap_years"]   = np.clip(65 - df["age_at_loan_maturity"], -20, 40)
    df["loan_per_dependent"]     = (df["loan_amount_lakhs"] / (df["dependents"] + 1)).round(4)
    df["cibil_foir_interaction"] = (df["cibil_score"] / (df["foir"] + 0.01)).round(2)
    df["loan_per_tenure"]        = (df["loan_amount_lakhs"] / df["tenure_months"]).round(4)
    df["credit_utilisation"]     = (
        df["no_of_existing_loans"] * df["existing_emi_lakhs"]
        / (df["monthly_income_lakhs"] + 1e-6)
    ).round(4)
    df["hard_reject_flag"]       = (
        (df["cibil_score"] < 550)
        | (df["foir"] > 0.70)
        | (df["previous_defaults"] >= 2)
    ).astype(int)
    return df


# ── EMI Calculator ─────────────────────────────────────────
def calc_emi(principal_lakhs, annual_rate_pct, tenure_months):
    P = principal_lakhs
    r = annual_rate_pct / (12 * 100)
    n = tenure_months
    if r == 0:
        return round(P / n, 4)
    return round(P * r * (1 + r) ** n / ((1 + r) ** n - 1), 4)


# ── /predict  POST endpoint ────────────────────────────────
@app.route("/predict", methods=["POST"])
def predict():
    try:
        data = request.get_json(force=True)

        # ── Derived fields (compute if not sent) ──────────
        annual_income  = float(data.get("annual_income_lakhs", 0))
        monthly_income = round(annual_income / 12, 4)
        loan_amount    = float(data.get("loan_amount_lakhs", 0))
        tenure         = int(data.get("tenure_months", 12))
        rate           = float(data.get("interest_rate_pct", 10))
        existing_emi   = float(data.get("existing_emi_lakhs", 0))
        age            = int(data.get("age", 30))

        emi  = calc_emi(loan_amount, rate, tenure)
        foir = round((emi + existing_emi) / (monthly_income or 0.001), 4)
        lti  = round(loan_amount / (annual_income or 0.001), 4)
        age_maturity = age + tenure // 12

        # Priority sector flag
        loan_type = data.get("loan_type", "Personal Loan")
        priority  = int(
            loan_type in ["Home Loan", "Education Loan", "Gold Loan"]
            or (loan_type == "Business Loan" and loan_amount <= 100)
        )

        record = {
            "age":                   age,
            "employment_type":       data.get("employment_type", "Salaried"),
            "years_employed":        int(data.get("years_employed", 0)),
            "annual_income_lakhs":   annual_income,
            "monthly_income_lakhs":  monthly_income,
            "dependents":            int(data.get("dependents", 0)),
            "state":                 data.get("state", "Andhra Pradesh"),
            "property_area":         data.get("property_area", "Urban"),
            "cibil_score":           int(data.get("cibil_score", 700)),
            "credit_history_years":  int(data.get("credit_history_years", 0)),
            "no_of_existing_loans":  int(data.get("no_of_existing_loans", 0)),
            "existing_emi_lakhs":    existing_emi,
            "previous_defaults":     int(data.get("previous_defaults", 0)),
            "bankruptcies":          int(data.get("bankruptcies", 0)),
            "loan_type":             loan_type,
            "loan_amount_lakhs":     loan_amount,
            "tenure_months":         tenure,
            "interest_rate_pct":     rate,
            "ltv_ratio":             float(data.get("ltv_ratio", 75)),
            "collateral_value_lakhs":float(data.get("collateral_value_lakhs", 0)),
            "priority_sector":       priority,
            "emi_lakhs":             emi,
            "foir":                  foir,
            "loan_to_income_ratio":  lti,
            "age_at_loan_maturity":  age_maturity,
        }

        df_app = pd.DataFrame([record])
        df_eng = engineer_features(df_app)

        # Encode categoricals
        for col, le in le_dict.items():
            if col in df_eng.columns:
                try:
                    df_eng[col] = le.transform(df_eng[col].astype(str))
                except ValueError:
                    df_eng[col] = 0

        # Align columns
        for col in feature_cols:
            if col not in df_eng.columns:
                df_eng[col] = 0
        df_eng = df_eng[feature_cols].astype(np.float32)

        proba    = float(model.predict_proba(df_eng)[0, 1])
        approved = bool(proba >= 0.5)

        # Hard reject override
        hard_reject = (
            record["cibil_score"] < 550
            or foir > 0.70
            or record["previous_defaults"] >= 2
            or (record["bankruptcies"] > 0 and record["credit_history_years"] < 3)
        )
        if hard_reject:
            approved = False
            proba    = min(proba, 0.15)

        # Risk factors
        factors = []
        if record["cibil_score"] >= 750:          factors.append({"factor": "CIBIL Score",         "status": "good",    "detail": f"{record['cibil_score']} — Excellent"})
        elif record["cibil_score"] >= 650:         factors.append({"factor": "CIBIL Score",         "status": "warn",    "detail": f"{record['cibil_score']} — Acceptable"})
        else:                                       factors.append({"factor": "CIBIL Score",         "status": "bad",     "detail": f"{record['cibil_score']} — Below threshold"})

        if foir <= 0.40:                            factors.append({"factor": "FOIR",                "status": "good",    "detail": f"{foir*100:.1f}% — Well within RBI limit"})
        elif foir <= 0.50:                          factors.append({"factor": "FOIR",                "status": "warn",    "detail": f"{foir*100:.1f}% — At RBI limit"})
        else:                                       factors.append({"factor": "FOIR",                "status": "bad",     "detail": f"{foir*100:.1f}% — Exceeds RBI comfort zone"})

        if monthly_income >= 3 * emi:               factors.append({"factor": "Income Coverage",     "status": "good",    "detail": f"{monthly_income/max(emi,0.001):.1f}x EMI covered"})
        elif monthly_income >= 2 * emi:             factors.append({"factor": "Income Coverage",     "status": "warn",    "detail": f"{monthly_income/max(emi,0.001):.1f}x EMI — Borderline"})
        else:                                       factors.append({"factor": "Income Coverage",     "status": "bad",     "detail": "Insufficient income vs EMI"})

        if record["previous_defaults"] == 0:        factors.append({"factor": "Default History",     "status": "good",    "detail": "Clean — No defaults"})
        elif record["previous_defaults"] == 1:      factors.append({"factor": "Default History",     "status": "warn",    "detail": "1 previous default"})
        else:                                       factors.append({"factor": "Default History",     "status": "bad",     "detail": f"{record['previous_defaults']} defaults — Hard reject"})

        if record["bankruptcies"] == 0:             factors.append({"factor": "Bankruptcy",          "status": "good",    "detail": "No bankruptcy history"})
        else:                                       factors.append({"factor": "Bankruptcy",          "status": "bad",     "detail": "Bankruptcy declared — Risk flag"})

        emp = record["employment_type"]
        if emp in ["Government", "PSU"]:            factors.append({"factor": "Employment Stability","status": "good",    "detail": f"{emp} — Highest stability"})
        elif record["years_employed"] >= 3:         factors.append({"factor": "Employment Stability","status": "good",    "detail": f"{record['years_employed']} years — Stable"})
        elif record["years_employed"] >= 1:         factors.append({"factor": "Employment Stability","status": "warn",    "detail": f"Only {record['years_employed']} year(s)"})
        else:                                       factors.append({"factor": "Employment Stability","status": "bad",     "detail": "Less than 1 year employed"})

        if lti <= 3:                                factors.append({"factor": "Loan/Income Ratio",   "status": "good",    "detail": f"{lti:.2f}x — Low burden"})
        elif lti <= 6:                              factors.append({"factor": "Loan/Income Ratio",   "status": "warn",    "detail": f"{lti:.2f}x — Moderate"})
        else:                                       factors.append({"factor": "Loan/Income Ratio",   "status": "bad",     "detail": f"{lti:.2f}x — High loan burden"})

        risk_level = "Low" if proba > 0.75 else "Medium" if proba > 0.5 else "High"
        if hard_reject:
            risk_level = "Very High"

        monthly_payment = round(emi * 100000)  # in rupees

        return jsonify({
            "approved":             approved,
            "probability":          round(proba * 100, 2),
            "risk_level":           risk_level,
            "hard_reject":          hard_reject,
            "computed": {
                "emi_lakhs":        round(emi, 4),
                "monthly_emi_rs":   monthly_payment,
                "foir_pct":         round(foir * 100, 2),
                "loan_to_income":   round(lti, 2),
                "age_at_maturity":  age_maturity,
                "monthly_income":   round(monthly_income, 4),
                "total_interest":   round((emi * tenure - loan_amount) * 100000),
                "priority_sector":  bool(priority)
            },
            "factors":              factors
        })

    except Exception as e:
        traceback.print_exc()
        return jsonify({"error": str(e)}), 500


